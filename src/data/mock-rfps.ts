import { type Rfp, type RfpFile, type SolicitationKind, Status } from "@/types/rfp";

const DAY_MS = 86400000;

function doc(
    rfpId: string,
    suffix: string,
    title: string,
    size: number,
    mimetype: string,
    ext: string,
    daysAgoUploaded: number,
): RfpFile {
    return {
        id: `${rfpId}-file-${suffix}`,
        title,
        size,
        mimetype,
        filename: `${rfpId}-${suffix}.${ext}`,
        url: `https://example.gov/procurement/${rfpId}/${suffix}.${ext}`,
        uploadedAt: new Date(Date.now() - daysAgoUploaded * DAY_MS),
    };
}

/** At least five attachments per solicitation (PDF, addenda, templates, etc.). */
function fiveDocsFor(rfpId: string): RfpFile[] {
    return [
        doc(rfpId, "solicitation", "Solicitation (complete packet)", 1_048_576, "application/pdf", "pdf", 28),
        doc(rfpId, "attachment-a", "Attachment A — Technical specifications", 512_000, "application/pdf", "pdf", 25),
        doc(rfpId, "addendum-1", "Addendum 01 — Scope clarifications", 189_440, "application/pdf", "pdf", 18),
        doc(rfpId, "pricing-wb", "Pricing and cost workbook (vendor)", 92_160, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "xlsx", 14),
        doc(rfpId, "insurance", "Insurance & bonding affidavit template", 61_440, "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "docx", 12),
    ];
}

type RfpSeed = Omit<Rfp, "files" | "publishedAt" | "questionsDueDate" | "preBidConferenceAt"> & {
    solicitationKind: SolicitationKind;
    publishedDaysAgo: number;
    questionsDaysBeforeDue: number;
    preBidDaysBeforeDue?: number;
};

function finalize(seed: RfpSeed): Rfp {
    const { publishedDaysAgo, questionsDaysBeforeDue, preBidDaysBeforeDue, ...rest } = seed;
    const questionsDue = new Date(seed.dueDate.getTime() - questionsDaysBeforeDue * DAY_MS);
    const publishedAt = new Date(Date.now() - publishedDaysAgo * DAY_MS);
    const preBid =
        preBidDaysBeforeDue !== undefined ? new Date(seed.dueDate.getTime() - preBidDaysBeforeDue * DAY_MS) : undefined;

    return {
        ...rest,
        publishedAt,
        questionsDueDate: questionsDue,
        preBidConferenceAt: preBid,
        files: fiveDocsFor(seed.id),
    };
}

